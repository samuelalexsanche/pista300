/** Torneos futuros respecto a una fecha, ordenados por proximidad. */
export function proximosTorneos(desde = "2026-09-06", limite?: number) {
  const lista = tournaments
    .filter((t) => t.fechaFin >= desde)
    .sort((a, b) => a.fechaInicio.localeCompare(b.fechaInicio));
  return limite ? lista.slice(0, limite) : lista;
}
